-- =============================================================================
-- 01_create_tables.sql
-- Features : F1 (normalised schema), F2 (integrity constraints), F3 (referential integrity)
-- Owner    : Member 1
-- RUN AS   : PRISON_OWNER, after 00_admin_setup.sql
--
-- Creates the SEVEN core tables from the specification, parent tables first:
--   BLOCKS -> INMATES -> VISITORS -> VISITS -> MOVEMENTS -> CONFLICTS -> AUDIT_LOG
-- Later scripts EVOLVE this base schema with ALTER TABLE (see 02_alter_schema.sql):
-- risk_level, facilities, conflict resolution flags, slot rules, ...
--
-- Delete rule (F3): every foreign key uses the default ON DELETE NO ACTION, which is
-- Oracle's equivalent of RESTRICT - a parent row with children cannot be deleted
-- (ORA-02292). History is preserved by changing STATUS instead of deleting rows.
-- All IDs are IDENTITY columns (GENERATED BY DEFAULT so the seed script may supply IDs).
-- =============================================================================
SET ECHO OFF
SET FEEDBACK ON

-- ---------------------------------------------------------------- BLOCKS
CREATE TABLE blocks (
  block_id        NUMBER GENERATED BY DEFAULT AS IDENTITY
                  CONSTRAINT pk_blocks PRIMARY KEY,
  block_name      VARCHAR2(50)  NOT NULL
                  CONSTRAINT uq_blocks_name UNIQUE,
  capacity        NUMBER(4)     NOT NULL
                  CONSTRAINT ck_blocks_capacity CHECK (capacity > 0),
  security_level  VARCHAR2(10)  NOT NULL
                  CONSTRAINT ck_blocks_security CHECK (security_level IN ('LOW','MEDIUM','HIGH'))
);

-- ---------------------------------------------------------------- INMATES
CREATE TABLE inmates (
  inmate_id       NUMBER GENERATED BY DEFAULT AS IDENTITY
                  CONSTRAINT pk_inmates PRIMARY KEY,
  inmate_no       VARCHAR2(20)  NOT NULL
                  CONSTRAINT uq_inmates_no UNIQUE,
  full_name       VARCHAR2(100) NOT NULL,
  date_of_birth   DATE          NOT NULL,
  admission_date  DATE          DEFAULT TRUNC(SYSDATE) NOT NULL,
  sentence_start  DATE          NOT NULL,
  sentence_end    DATE          NOT NULL,
  status          VARCHAR2(12)  DEFAULT 'ACTIVE' NOT NULL
                  CONSTRAINT ck_inmates_status CHECK (status IN ('ACTIVE','TRANSFERRED','RELEASED')),
  block_id        NUMBER        NOT NULL
                  CONSTRAINT fk_inmates_block REFERENCES blocks (block_id),
  CONSTRAINT ck_inmates_sentence CHECK (sentence_end > sentence_start)
);

-- ---------------------------------------------------------------- VISITORS
CREATE TABLE visitors (
  visitor_id       NUMBER GENERATED BY DEFAULT AS IDENTITY
                   CONSTRAINT pk_visitors PRIMARY KEY,
  full_name        VARCHAR2(100) NOT NULL,
  id_proof_type    VARCHAR2(20)  NOT NULL
                   CONSTRAINT ck_visitors_idtype
                   CHECK (id_proof_type IN ('PASSPORT','NATIONAL_ID','DRIVING_LICENCE','VOTER_ID')),
  id_proof_number  VARCHAR2(30)  NOT NULL,
  phone            VARCHAR2(20),
  approval_status  VARCHAR2(12)  DEFAULT 'PENDING' NOT NULL
                   CONSTRAINT ck_visitors_approval
                   CHECK (approval_status IN ('PENDING','APPROVED','REJECTED','BLACKLISTED')),
  registered_on    DATE          DEFAULT TRUNC(SYSDATE) NOT NULL,
  CONSTRAINT uq_visitors_idproof UNIQUE (id_proof_type, id_proof_number)
);

-- ---------------------------------------------------------------- VISITS
-- Associative table resolving the many-to-many link INMATES <-> VISITORS.
CREATE TABLE visits (
  visit_id    NUMBER GENERATED BY DEFAULT AS IDENTITY
              CONSTRAINT pk_visits PRIMARY KEY,
  inmate_id   NUMBER        NOT NULL
              CONSTRAINT fk_visits_inmate  REFERENCES inmates (inmate_id),
  visitor_id  NUMBER        NOT NULL
              CONSTRAINT fk_visits_visitor REFERENCES visitors (visitor_id),
  visit_date  DATE          NOT NULL
              CONSTRAINT ck_visits_date_only CHECK (visit_date = TRUNC(visit_date)),
  slot        VARCHAR2(11)  NOT NULL
              CONSTRAINT ck_visits_slot
              CHECK (slot IN ('09:00-10:00','10:00-11:00','11:00-12:00',
                              '14:00-15:00','15:00-16:00','16:00-17:00')),
  status      VARCHAR2(10)  DEFAULT 'SCHEDULED' NOT NULL
              CONSTRAINT ck_visits_status
              CHECK (status IN ('SCHEDULED','COMPLETED','MISSED','CANCELLED')),
  booked_on   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_visits_inmate_slot UNIQUE (inmate_id, visit_date, slot)
);

-- ---------------------------------------------------------------- MOVEMENTS
-- MOVEMENTS references BLOCKS twice: origin (from_block, NULL on admission) and destination.
CREATE TABLE movements (
  movement_id    NUMBER GENERATED BY DEFAULT AS IDENTITY
                 CONSTRAINT pk_movements PRIMARY KEY,
  inmate_id      NUMBER        NOT NULL
                 CONSTRAINT fk_mov_inmate REFERENCES inmates (inmate_id),
  from_block     NUMBER
                 CONSTRAINT fk_mov_from   REFERENCES blocks (block_id),
  to_block       NUMBER        NOT NULL
                 CONSTRAINT fk_mov_to     REFERENCES blocks (block_id),
  movement_date  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  reason         VARCHAR2(200),
  moved_by       VARCHAR2(60)  DEFAULT SYS_CONTEXT('USERENV','SESSION_USER') NOT NULL,
  CONSTRAINT ck_mov_diff CHECK (from_block IS NULL OR from_block <> to_block)
);

-- ---------------------------------------------------------------- CONFLICTS
-- Associative table: a visitor who must never meet a given inmate.
CREATE TABLE conflicts (
  conflict_id   NUMBER GENERATED BY DEFAULT AS IDENTITY
                CONSTRAINT pk_conflicts PRIMARY KEY,
  inmate_id     NUMBER        NOT NULL
                CONSTRAINT fk_conf_inmate  REFERENCES inmates (inmate_id),
  visitor_id    NUMBER        NOT NULL
                CONSTRAINT fk_conf_visitor REFERENCES visitors (visitor_id),
  reason        VARCHAR2(20)  NOT NULL
                CONSTRAINT ck_conf_reason
                CHECK (reason IN ('RIVAL','VICTIM_RELATIVE','GANG_AFFILIATION','OTHER')),
  flagged_date  DATE          DEFAULT TRUNC(SYSDATE) NOT NULL,
  CONSTRAINT uq_conf_pair UNIQUE (inmate_id, visitor_id)
);

-- ---------------------------------------------------------------- AUDIT_LOG
-- Deliberately has NO foreign keys: audit rows must survive whatever happens to the
-- rows they describe, and denied attempts are logged for records that were never created.
CREATE TABLE audit_log (
  audit_id     NUMBER GENERATED BY DEFAULT AS IDENTITY
               CONSTRAINT pk_audit_log PRIMARY KEY,
  table_name   VARCHAR2(30)   NOT NULL,
  action_type  VARCHAR2(20)   NOT NULL
               CONSTRAINT ck_audit_action
               CHECK (action_type IN ('INSERT','UPDATE','DELETE','TRANSFER',
                                      'VISIT_BOOKED','VISIT_DENIED','JOB')),
  record_id    NUMBER,
  details      VARCHAR2(4000),
  changed_by   VARCHAR2(60)   DEFAULT SYS_CONTEXT('USERENV','SESSION_USER') NOT NULL,
  changed_at   TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL
);

