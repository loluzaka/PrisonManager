-- ---------------------------------------------------------------- 5. movements and transfers
-- Every inmate has an ADMISSION movement. Eight inmates were also transferred between blocks:
-- admission block = MOD(current,5)+1 (always different from the current block).
DECLARE
  TYPE t_ids IS VARRAY(8) OF NUMBER;
  c_transferred CONSTANT t_ids := t_ids(2, 9, 16, 21, 33, 36, 44, 46);
  v_cur   NUMBER;
  v_adm   NUMBER;
  v_start DATE;
  v_is_tr BOOLEAN;
  v_idx   NUMBER;
BEGIN
  FOR r IN (SELECT inmate_id, block_id, sentence_start FROM inmates ORDER BY inmate_id) LOOP
    v_is_tr := FALSE;
    FOR k IN 1 .. c_transferred.COUNT LOOP
      IF c_transferred(k) = r.inmate_id THEN v_is_tr := TRUE; v_idx := k; END IF;
    END LOOP;
    IF v_is_tr THEN
      v_adm := MOD(r.block_id, 5) + 1;
      INSERT INTO movements (inmate_id, from_block, to_block, movement_date, reason, moved_by)
        VALUES (r.inmate_id, NULL, v_adm, CAST(r.sentence_start AS TIMESTAMP), 'ADMISSION', 'SEED');
      INSERT INTO movements (inmate_id, from_block, to_block, movement_date, reason, moved_by)
        VALUES (r.inmate_id, v_adm, r.block_id, SYSTIMESTAMP - NUMTODSINTERVAL(10 + v_idx * 7, 'DAY'),
                'Behaviour review transfer', 'SEED');
      INSERT INTO audit_log (table_name, action_type, record_id, details, changed_by, changed_at)
        VALUES ('INMATES', 'TRANSFER', r.inmate_id,
                'Block ' || v_adm || ' -> ' || r.block_id || '; reason=Behaviour review transfer',
                'SEED', SYSTIMESTAMP - NUMTODSINTERVAL(10 + v_idx * 7, 'DAY'));
    ELSE
      INSERT INTO movements (inmate_id, from_block, to_block, movement_date, reason, moved_by)
        VALUES (r.inmate_id, NULL, r.block_id, CAST(r.sentence_start AS TIMESTAMP), 'ADMISSION', 'SEED');
    END IF;
  END LOOP;
END;
/

-- ---------------------------------------------------------------- 6. visits (100)
-- Generated deterministically but only kept if every business rule holds:
-- approved visitor, ACTIVE inmate, no ACTIVE conflict, inside the sentence, no duplicate,
-- <= 3 visits per inmate per ISO week, <= 5 visits per date+slot.
DECLARE
  TYPE t_slots IS VARRAY(6) OF VARCHAR2(11);
  c_slot CONSTANT t_slots := t_slots('09:00-10:00','10:00-11:00','11:00-12:00','14:00-15:00','15:00-16:00','16:00-17:00');
  v_n     NUMBER := 0;
  v_k     NUMBER := 0;
  v_inm   NUMBER;
  v_vis   NUMBER;
  v_date  DATE;
  v_slot  VARCHAR2(11);
  v_stat  VARCHAR2(10);
  v_cnt   NUMBER;
  v_today CONSTANT DATE := TRUNC(SYSDATE);
BEGIN
  WHILE v_n < 100 AND v_k < 5000 LOOP
    v_k    := v_k + 1;
    v_inm  := MOD(v_k * 7 + FLOOR(v_k / 45), 45) + 1;   -- ACTIVE inmates 1..45
    v_vis  := MOD(v_k * 11 + FLOOR(v_k / 30) * 3, 30) + 1;   -- APPROVED visitors 1..30
    v_slot := c_slot(MOD(v_k * 3 + FLOOR(v_k / 6), 6) + 1);
    IF v_n < 8 THEN                          -- 8 visits today (roster demo)
      v_date := v_today;                     v_stat := 'SCHEDULED';
    ELSIF v_n < 14 THEN                      -- 6 visits in the next 3 days
      v_date := v_today + 1 + MOD(v_n, 3);   v_stat := 'SCHEDULED';
    ELSE                                     -- history over the last 80 days
      v_date := v_today - 1 - MOD(v_k * 5 + FLOOR(v_k / 16) * 3, 80);
      v_stat := CASE MOD(v_k, 25) WHEN 0 THEN 'MISSED' WHEN 1 THEN 'CANCELLED' ELSE 'COMPLETED' END;
    END IF;

    SELECT COUNT(*) INTO v_cnt FROM conflicts c
     WHERE c.inmate_id = v_inm AND c.visitor_id = v_vis AND c.resolved = 'N'
       AND (c.expiry_date IS NULL OR c.expiry_date >= v_today);
    CONTINUE WHEN v_cnt > 0;
    SELECT COUNT(*) INTO v_cnt FROM inmates i
     WHERE i.inmate_id = v_inm AND v_date BETWEEN i.sentence_start AND i.sentence_end;
    CONTINUE WHEN v_cnt = 0;
    SELECT COUNT(*) INTO v_cnt FROM visits
     WHERE inmate_id = v_inm AND visit_date = v_date AND slot = v_slot;
    CONTINUE WHEN v_cnt > 0;
    SELECT COUNT(*) INTO v_cnt FROM visits
     WHERE inmate_id = v_inm AND status <> 'CANCELLED' AND TRUNC(visit_date, 'IW') = TRUNC(v_date, 'IW');
    CONTINUE WHEN v_cnt >= 3;
    SELECT COUNT(*) INTO v_cnt FROM visits
     WHERE visit_date = v_date AND slot = v_slot AND status <> 'CANCELLED';
    CONTINUE WHEN v_cnt >= 5;

    INSERT INTO visits (visit_id, inmate_id, visitor_id, visit_date, slot, status, booked_on)
    VALUES (v_n + 1, v_inm, v_vis, v_date, v_slot, v_stat,
            CAST(v_date - 3 AS TIMESTAMP));
    v_n := v_n + 1;
  END LOOP;
  DBMS_OUTPUT.PUT_LINE('visits generated: ' || v_n || ' (candidates tried: ' || v_k || ')');
END;
