-- *** RESET SCRIPT *** Re-running it DELETES all inmates, visitors, visits, movements,
-- conflicts and audit rows and rebuilds the same synthetic dataset. It can therefore be run
-- at any time, even after the triggers exist (it disables them while loading).
--
-- ALL DATA IS SYNTHETIC. Names are generated from generic word lists, ID numbers are fake
-- ("SYN-nnnnnn"), no real person is represented.
--
-- Dataset: 2 facilities, 5 blocks, 50 inmates (45 ACTIVE, 2 TRANSFERRED, 3 RELEASED),
--          40 visitors (30 APPROVED, 5 PENDING, 3 BLACKLISTED, 2 REJECTED), 100 visits,
--          8 visitor conflicts, 3 inmate rivalries, 58 movements, history in AUDIT_LOG.
-- Dates are relative to SYSDATE so the data never goes stale (visits today / tomorrow exist).
-- =============================================================================
SET SERVEROUTPUT ON SIZE UNLIMITED
SET FEEDBACK OFF
SET VERIFY OFF

-- ---------------------------------------------------------------- 1. disable triggers
BEGIN
  FOR t IN (SELECT trigger_name FROM user_triggers WHERE status = 'ENABLED') LOOP
    EXECUTE IMMEDIATE 'ALTER TRIGGER ' || t.trigger_name || ' DISABLE';
  END LOOP;
END;
/

-- ---------------------------------------------------------------- 2. reset (children first)
DELETE FROM visits;
DELETE FROM conflicts;
DELETE FROM inmate_conflicts;
DELETE FROM movements;
DELETE FROM inmates;
DELETE FROM visitors;
-- DDL: does not fire row triggers, so it works even though audit rows are append-only
TRUNCATE TABLE audit_log;
ALTER TABLE audit_log MODIFY audit_id GENERATED BY DEFAULT AS IDENTITY (RESTART START WITH 1);
-- tables whose seed rows get their IDs from the identity generator: start counting at 1 again
ALTER TABLE movements        MODIFY movement_id GENERATED BY DEFAULT AS IDENTITY (RESTART START WITH 1);
ALTER TABLE conflicts        MODIFY conflict_id GENERATED BY DEFAULT AS IDENTITY (RESTART START WITH 1);
ALTER TABLE inmate_conflicts MODIFY rivalry_id  GENERATED BY DEFAULT AS IDENTITY (RESTART START WITH 1);

-- ---------------------------------------------------------------- 3. facilities and blocks (MERGE = repeatable)
MERGE INTO facilities f
USING (SELECT 1 id, 'Central Correctional Facility' nm, 'Metropolis' ct FROM dual UNION ALL
       SELECT 2,   'Riverside Detention Centre',        'Rivertown'      FROM dual) s
ON (f.facility_id = s.id)
WHEN NOT MATCHED THEN INSERT (facility_id, facility_name, city) VALUES (s.id, s.nm, s.ct);

MERGE INTO blocks b
USING (SELECT 1 id, 'A-Block' nm, 14 cap, 'LOW'    sec, 1 fac FROM dual UNION ALL
       SELECT 2, 'B-Block', 12, 'MEDIUM', 1 FROM dual UNION ALL
       SELECT 3, 'C-Block',  8, 'HIGH',   1 FROM dual UNION ALL
       SELECT 4, 'D-Block', 10, 'LOW',    2 FROM dual UNION ALL
       SELECT 5, 'E-Block',  6, 'MEDIUM', 2 FROM dual) s
ON (b.block_id = s.id)
WHEN MATCHED THEN UPDATE SET b.block_name = s.nm, b.capacity = s.cap,
                             b.security_level = s.sec, b.facility_id = s.fac
WHEN NOT MATCHED THEN INSERT (block_id, block_name, capacity, security_level, facility_id)
                      VALUES (s.id, s.nm, s.cap, s.sec, s.fac);

-- ---------------------------------------------------------------- 4. inmates, visitors, conflicts
DECLARE
  TYPE t_names IS VARRAY(25) OF VARCHAR2(20);
  c_first CONSTANT t_names := t_names('Arjun','Bilal','Chen','Dmitri','Ethan','Farid','Gabriel','Hassan','Ivan','Jamal',
                                      'Karan','Liam','Mateo','Nikhil','Omar','Pavel','Qasim','Rohan','Samuel','Tariq',
                                      'Umar','Viktor','Wen','Yusuf','Zane');
  c_last  CONSTANT t_names := t_names('Ahmed','Brown','Chatterjee','Dubois','Evans','Fischer','Garcia','Hussain','Ibrahim','Jensen',
                                      'Khan','Lopez','Mehta','Novak','Okafor','Patel','Quinn','Rossi','Singh','Tanaka',
                                      'Usman','Verma','Walker','Xu','Young');
  TYPE t_types IS VARRAY(4) OF VARCHAR2(20);
  c_idtype CONSTANT t_types := t_types('PASSPORT','NATIONAL_ID','DRIVING_LICENCE','VOTER_ID');

  v_block   NUMBER;
  v_status  VARCHAR2(12);
  v_risk    VARCHAR2(10);
  v_start   DATE;
  v_end     DATE;
  v_today   CONSTANT DATE := TRUNC(SYSDATE);
BEGIN
  FOR i IN 1 .. 50 LOOP
    -- block layout: A 1-12, B 13-23, C 24-30, D 31-39, E 40-45 (all ACTIVE); 46-50 are not active
    v_block := CASE WHEN i <= 12 THEN 1 WHEN i <= 23 THEN 2 WHEN i <= 30 THEN 3
                    WHEN i <= 39 THEN 4 WHEN i <= 45 THEN 5
                    WHEN i = 46 THEN 1 WHEN i = 47 THEN 4 WHEN i = 48 THEN 2
                    WHEN i = 49 THEN 1 ELSE 5 END;
    v_status := CASE WHEN i <= 45 THEN 'ACTIVE' WHEN i <= 47 THEN 'TRANSFERRED' ELSE 'RELEASED' END;
    -- risk must not exceed the block security level (LOW blocks A,D -> LOW only)
    v_risk := CASE v_block
                WHEN 1 THEN 'LOW'  WHEN 4 THEN 'LOW'
                WHEN 2 THEN CASE WHEN MOD(i,3) = 0 THEN 'MEDIUM' ELSE 'LOW' END
                WHEN 5 THEN CASE WHEN MOD(i,2) = 0 THEN 'MEDIUM' ELSE 'LOW' END
                ELSE        CASE MOD(i,3) WHEN 0 THEN 'HIGH' WHEN 1 THEN 'MEDIUM' ELSE 'LOW' END
              END;
    IF i IN (3, 14, 19, 27, 33, 41) THEN        -- due for release soon (8 .. 46 days)
      v_end   := v_today + 5 + i;
      v_start := v_end - 1500;
    ELSIF i >= 48 THEN                           -- already released
      v_end   := v_today - 10 * (i - 47);
      v_start := v_end - 700;
    ELSE
      v_start := v_today - 100 - MOD(i * 37, 700);
      v_end   := v_start + 1000 + MOD(i * 91, 2500);
    END IF;

    INSERT INTO inmates (inmate_id, inmate_no, full_name, date_of_birth, admission_date,
                         sentence_start, sentence_end, status, block_id, risk_level)
    VALUES (i, 'INM-' || LPAD(i, 4, '0'),
            c_first(MOD(i * 3, 25) + 1) || ' ' || c_last(MOD(i * 7, 25) + 1),
            ADD_MONTHS(v_today, -12 * (22 + MOD(i * 7, 35))) - MOD(i * 11, 300),
            v_start, v_start, v_end, v_status, v_block, v_risk);
  END LOOP;

  FOR i IN 1 .. 40 LOOP
    INSERT INTO visitors (visitor_id, full_name, id_proof_type, id_proof_number, phone, approval_status, registered_on)
    VALUES (i,
            c_first(MOD(i * 5 + 2, 25) + 1) || ' ' || c_last(MOD(i * 11 + 3, 25) + 1),
            c_idtype(MOD(i, 4) + 1),
            'SYN-' || LPAD(MOD(i * 7919, 1000000), 6, '0'),
            '+00-555-' || LPAD(i, 4, '0'),
            CASE WHEN i <= 30 THEN 'APPROVED' WHEN i <= 35 THEN 'PENDING'
                 WHEN i <= 38 THEN 'BLACKLISTED' ELSE 'REJECTED' END,
            v_today - 200 + i);
  END LOOP;
END;
