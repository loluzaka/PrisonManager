DECLARE
  PROCEDURE restart_identity(p_table VARCHAR2, p_col VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' MODIFY ' || p_col ||
                      ' GENERATED BY DEFAULT AS IDENTITY (RESTART START WITH LIMIT VALUE)';
  END;
BEGIN
  -- constraint added AFTER the data was loaded (F4); ORA-01442 = already NOT NULL on a re-run
  BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE blocks MODIFY (facility_id NOT NULL)';
  EXCEPTION WHEN OTHERS THEN
    IF SQLCODE <> -1442 THEN RAISE; END IF;
  END;
  restart_identity('facilities', 'facility_id');
  restart_identity('blocks',     'block_id');
  restart_identity('inmates',    'inmate_id');
  restart_identity('visitors',   'visitor_id');
  restart_identity('visits',     'visit_id');
  restart_identity('conflicts',  'conflict_id');
  restart_identity('movements',  'movement_id');
  restart_identity('inmate_conflicts', 'rivalry_id');
  restart_identity('audit_log',  'audit_id');
  FOR t IN (SELECT trigger_name FROM user_triggers WHERE status = 'DISABLED') LOOP
    EXECUTE IMMEDIATE 'ALTER TRIGGER ' || t.trigger_name || ' ENABLE';
  END LOOP;
END;
/
