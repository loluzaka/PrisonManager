SET ECHO OFF
SET FEEDBACK ON

-- ---------------------------------------------------------------- F31 FACILITIES
CREATE TABLE facilities (
  facility_id    NUMBER GENERATED BY DEFAULT AS IDENTITY
                 CONSTRAINT pk_facilities PRIMARY KEY,
  facility_name  VARCHAR2(100) NOT NULL CONSTRAINT uq_facilities_name UNIQUE,
  city           VARCHAR2(60)  NOT NULL
);

-- Added NULLABLE first; the seed script loads data and THEN makes it NOT NULL
-- (the "add constraints after loading data" technique from F4).
ALTER TABLE blocks ADD (
  facility_id NUMBER CONSTRAINT fk_blocks_facility REFERENCES facilities (facility_id)
);

-- ---------------------------------------------------------------- F15 RISK LEVEL
ALTER TABLE inmates ADD (
  risk_level VARCHAR2(10) DEFAULT 'LOW' NOT NULL
             CONSTRAINT ck_inmates_risk CHECK (risk_level IN ('LOW','MEDIUM','HIGH'))
);

-- ---------------------------------------------------------------- F14 CONFLICT LIFECYCLE
ALTER TABLE conflicts ADD (
  resolved     CHAR(1) DEFAULT 'N' NOT NULL CONSTRAINT ck_conf_resolved CHECK (resolved IN ('Y','N')),
  resolved_on  DATE,
  expiry_date  DATE
);
ALTER TABLE conflicts ADD CONSTRAINT ck_conf_expiry
  CHECK (expiry_date IS NULL OR expiry_date >= flagged_date);

-- Rivalry between two inmates: rivals must never be housed in the same block.
-- inmate_a < inmate_b stores each pair exactly once.
CREATE TABLE inmate_conflicts (
  rivalry_id    NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_inmate_conflicts PRIMARY KEY,
  inmate_a      NUMBER        NOT NULL CONSTRAINT fk_ic_a REFERENCES inmates (inmate_id),
  inmate_b      NUMBER        NOT NULL CONSTRAINT fk_ic_b REFERENCES inmates (inmate_id),
  reason        VARCHAR2(20)  NOT NULL
                CONSTRAINT ck_ic_reason CHECK (reason IN ('RIVAL','GANG_AFFILIATION','OTHER')),
  flagged_date  DATE          DEFAULT TRUNC(SYSDATE) NOT NULL,
  resolved      CHAR(1)       DEFAULT 'N' NOT NULL CONSTRAINT ck_ic_resolved CHECK (resolved IN ('Y','N')),
  CONSTRAINT ck_ic_order CHECK (inmate_a < inmate_b),
  CONSTRAINT uq_ic_pair  UNIQUE (inmate_a, inmate_b)
);

-- ---------------------------------------------------------------- F16 VISIT SLOTS
-- Reference table: capacity of each fixed slot. VISITS.slot is still protected by a CHECK list
-- (script 01); this table adds max_visitors and gives sp_schedule_visit a row to lock.
CREATE TABLE visit_slots (
  slot_code     VARCHAR2(11) CONSTRAINT pk_visit_slots PRIMARY KEY,
  start_time    VARCHAR2(5)  NOT NULL,
  end_time      VARCHAR2(5)  NOT NULL,
  max_visitors  NUMBER(3)    DEFAULT 5 NOT NULL CONSTRAINT ck_slots_max CHECK (max_visitors > 0)
);
