-- ---------------------------------------------------------------- F31 STAFF ACCESS
-- Maps a database login to the facility whose rows it may see (NULL = all facilities).
CREATE TABLE staff_access (
  db_username  VARCHAR2(30) CONSTRAINT pk_staff_access PRIMARY KEY,
  facility_id  NUMBER       CONSTRAINT fk_staff_facility REFERENCES facilities (facility_id)
);

-- ---------------------------------------------------------------- F4 DEMO: TRUNCATE and DROP
-- A throw-away copy of VISITS shows TRUNCATE (removes all rows, cannot be rolled back,
-- resets the high-water mark) versus DROP (removes the table itself).
CREATE TABLE tmp_visit_test AS SELECT * FROM visits WHERE 1 = 0;
INSERT INTO tmp_visit_test (visit_id, inmate_id, visitor_id, visit_date, slot, status, booked_on)
  VALUES (1, 1, 1, TRUNC(SYSDATE), '09:00-10:00', 'SCHEDULED', SYSTIMESTAMP);
SELECT COUNT(*) AS rows_before_truncate FROM tmp_visit_test;
TRUNCATE TABLE tmp_visit_test;
SELECT COUNT(*) AS rows_after_truncate FROM tmp_visit_test;
DROP TABLE tmp_visit_test PURGE;

