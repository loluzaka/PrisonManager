CREATE TABLE facilities (
    facility_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facility_name varchar(100) NOT NULL UNIQUE,
    city varchar(60) NOT NULL
);

CREATE TABLE blocks (
    block_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    block_name varchar(50) NOT NULL UNIQUE,
    capacity integer NOT NULL CHECK (capacity > 0),
    security_level varchar(10) NOT NULL CHECK (security_level IN ('LOW', 'MEDIUM', 'HIGH')),
    facility_id bigint NOT NULL REFERENCES facilities (facility_id)
);

CREATE TABLE inmates (
    inmate_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inmate_no varchar(20) NOT NULL UNIQUE,
    full_name varchar(100) NOT NULL,
    date_of_birth date NOT NULL,
    admission_date date NOT NULL DEFAULT CURRENT_DATE,
    sentence_start date NOT NULL,
    sentence_end date NOT NULL,
    status varchar(12) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'TRANSFERRED', 'RELEASED')),
    block_id bigint NOT NULL REFERENCES blocks (block_id),
    risk_level varchar(10) NOT NULL DEFAULT 'LOW'
        CHECK (risk_level IN ('LOW', 'MEDIUM', 'HIGH')),
    CHECK (sentence_end > sentence_start)
);

CREATE TABLE visitors (
    visitor_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name varchar(100) NOT NULL,
    id_proof_type varchar(20) NOT NULL
        CHECK (id_proof_type IN ('PASSPORT', 'NATIONAL_ID', 'DRIVING_LICENCE', 'VOTER_ID')),
    id_proof_number varchar(30) NOT NULL,
    phone varchar(20),
    approval_status varchar(12) NOT NULL DEFAULT 'PENDING'
        CHECK (approval_status IN ('PENDING', 'APPROVED', 'REJECTED', 'BLACKLISTED')),
    registered_on date NOT NULL DEFAULT CURRENT_DATE,
    UNIQUE (id_proof_type, id_proof_number)
);

CREATE TABLE visits (
    visit_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inmate_id bigint NOT NULL REFERENCES inmates (inmate_id),
    visitor_id bigint NOT NULL REFERENCES visitors (visitor_id),
    visit_date date NOT NULL,
    slot varchar(11) NOT NULL CHECK (
        slot IN ('09:00-10:00', '10:00-11:00', '11:00-12:00',
                 '14:00-15:00', '15:00-16:00', '16:00-17:00')
    ),
    status varchar(10) NOT NULL DEFAULT 'SCHEDULED'
        CHECK (status IN ('SCHEDULED', 'COMPLETED', 'MISSED', 'CANCELLED')),
    booked_on timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (inmate_id, visit_date, slot)
);

CREATE TABLE movements (
    movement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inmate_id bigint NOT NULL REFERENCES inmates (inmate_id),
    from_block bigint REFERENCES blocks (block_id),
    to_block bigint NOT NULL REFERENCES blocks (block_id),
    movement_date timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reason varchar(200),
    moved_by varchar(60) NOT NULL DEFAULT session_user,
    CHECK (from_block IS NULL OR from_block <> to_block)
);

CREATE TABLE conflicts (
    conflict_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inmate_id bigint NOT NULL REFERENCES inmates (inmate_id),
    visitor_id bigint NOT NULL REFERENCES visitors (visitor_id),
    reason varchar(20) NOT NULL
        CHECK (reason IN ('RIVAL', 'VICTIM_RELATIVE', 'GANG_AFFILIATION', 'OTHER')),
    flagged_date date NOT NULL DEFAULT CURRENT_DATE,
    resolved char(1) NOT NULL DEFAULT 'N' CHECK (resolved IN ('Y', 'N')),
    resolved_on date,
    expiry_date date,
    UNIQUE (inmate_id, visitor_id),
    CHECK (expiry_date IS NULL OR expiry_date >= flagged_date)
);

CREATE TABLE audit_log (
    audit_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name varchar(30) NOT NULL,
    action_type varchar(20) NOT NULL
        CHECK (action_type IN ('INSERT', 'UPDATE', 'DELETE', 'TRANSFER',
                               'VISIT_BOOKED', 'VISIT_DENIED', 'JOB')),
    record_id bigint,
    details varchar(4000),
    changed_by varchar(60) NOT NULL DEFAULT session_user,
    changed_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE inmate_conflicts (
    rivalry_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inmate_a bigint NOT NULL REFERENCES inmates (inmate_id),
    inmate_b bigint NOT NULL REFERENCES inmates (inmate_id),
    reason varchar(20) NOT NULL CHECK (reason IN ('RIVAL', 'GANG_AFFILIATION', 'OTHER')),
    flagged_date date NOT NULL DEFAULT CURRENT_DATE,
    resolved char(1) NOT NULL DEFAULT 'N' CHECK (resolved IN ('Y', 'N')),
    CHECK (inmate_a < inmate_b),
    UNIQUE (inmate_a, inmate_b)
);

CREATE TABLE visit_slots (
    slot_code varchar(11) PRIMARY KEY,
    start_time time NOT NULL,
    end_time time NOT NULL,
    max_visitors integer NOT NULL DEFAULT 5 CHECK (max_visitors > 0),
    CHECK (end_time > start_time)
);

CREATE TABLE staff_access (
    db_username varchar(63) PRIMARY KEY,
    facility_id bigint REFERENCES facilities (facility_id)
);

CREATE INDEX idx_inmates_block ON inmates (block_id);
CREATE INDEX idx_inmates_status ON inmates (status);
CREATE INDEX idx_visits_date ON visits (visit_date);
CREATE INDEX idx_visits_inmate_date ON visits (inmate_id, visit_date);
CREATE INDEX idx_visits_visitor ON visits (visitor_id);
CREATE INDEX idx_movements_inmate ON movements (inmate_id);
CREATE INDEX idx_movements_to_block ON movements (to_block);
CREATE INDEX idx_audit_table_record ON audit_log (table_name, record_id);
CREATE INDEX idx_audit_action ON audit_log (action_type, changed_at);
CREATE INDEX idx_blocks_facility ON blocks (facility_id);
